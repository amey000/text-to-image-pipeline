# 1. EVALUATION SUITE

class LISAEvaluator:
    """
    Handles the quantitative and qualitative evaluation of the pipeline.
    """
    def __init__(self, device="cuda"):
        print("Initializing Evaluation Suite (CLIP)...")
        self.device = device
        self.clip_model = CLIPModel.from_pretrained("openai/clip-vit-base-patch32").to(device)
        self.clip_processor = CLIPProcessor.from_pretrained("openai/clip-vit-base-patch32")

    def calculate_clip_score(self, image, text):
        """Calculates the alignment score between the image and the prompt."""
        inputs = self.clip_processor(text=[text], images=image, return_tensors="pt", padding=True).to(self.device)
        with torch.no_grad():
            outputs = self.clip_model(**inputs)

        # Cosine similarity score (normalized to 0-100 range)
        logits_per_image = outputs.logits_per_image
        score = logits_per_image.item()
        return round(score, 2)

    def judge_reasoning(self, client, original, expanded):
        """Uses LLM-as-a-judge to evaluate the LISA expansion quality."""
        prompt = (
            f"Compare the original intent with the expanded LISA prompt.\n"
            f"Original: {original}\nExpanded: {expanded}\n"
            f"Evaluate if the expansion adds useful COCO-style spatial and material details. "
            f"Rate from 1-10 and give a 1-sentence justification."
        )
        try:
            response = client.chat.completions.create(
                model="gpt-3.5-turbo",
                messages=[{"role": "user", "content": prompt}]
            )
            return response.choices[0].message.content
        except:
            return "Evaluation unavailable."

# 2. CORE PIPELINE CLASS (OpenAI Version)

class LISAProjectOpenAI:
    def __init__(self, openai_key, hf_token, lora_path):
        self.lora_path = lora_path
        self.client = OpenAI(api_key=openai_key)

        # Load Base Model on T4 GPU
        print("Loading Stable Diffusion Base Model...")
        self.pipe = StableDiffusionPipeline.from_pretrained(
            "stable-diffusion-v1-5/stable-diffusion-v1-5",
            torch_dtype=torch.float16,
            use_auth_token=hf_token
        ).to("cuda")

        # Initialize Evaluator
        self.evaluator = LISAEvaluator(device="cuda")

        # Load LoRA Weights
        self.has_lora = False
        if os.path.exists(self.lora_path):
            if os.path.isdir(self.lora_path):
                if "pytorch_lora_weights.safetensors" in os.listdir(self.lora_path):
                    self.has_lora = True
            else:
                self.has_lora = True

        if self.has_lora:
            self.pipe.load_lora_weights(self.lora_path)
            print(f"SUCCESSFULLY LOADED LOCAL COCO WEIGHTS.")
        else:
            print(f"WARNING: Weights not found at {self.lora_path}. Running base model.")

        self.pipe.scheduler = DPMSolverMultistepScheduler.from_config(self.pipe.scheduler.config)
        print("Pipeline Initialized.")

    def generate_result(self, user_intent, output_widget, use_lora=True):
        with output_widget:
            print(f"\nSTEP 1: LISA (OpenAI) is performing Semantic Expansion...")

            system_instruction = (
                "You are a LISA reasoning agent. Your task is to expand user prompts into "
                "high-detail descriptions focused on spatial relations (next to, on top of, inside) "
                "grounded in the COCO dataset semantics. "
                "IMPORTANT: Output your response exactly in this format:\n"
                "PROMPT: [your expanded prompt] | NEGATIVE: [things to avoid]"
            )

            try:
                response = self.client.chat.completions.create(
                    model="gpt-4",
                    messages=[
                        {"role": "system", "content": system_instruction},
                        {"role": "user", "content": user_intent}
                    ]
                )
                content = response.choices[0].message.content
                expanded_prompt = content.split("PROMPT:")[1].split("|")[0].strip()
                negative_prompt = content.split("NEGATIVE:")[1].strip()
            except Exception as e:
                print(f"OpenAI processing failed. Using fallback.")
                expanded_prompt = f"{user_intent}, high quality, highly detailed, COCO style"
                negative_prompt = "blurry, low quality, distorted"

            print(f" LISA Expanded Prompt: {expanded_prompt}")

            # Toggle LoRA for evaluation comparison if requested
            if not use_lora and self.has_lora:
                self.pipe.unload_lora_weights()
                print("Temporarily unloading LoRA for baseline comparison...")

            print(f"\n STEP 2: Rendering pixels...")
            image = self.pipe(
                prompt=expanded_prompt,
                negative_prompt=negative_prompt,
                num_inference_steps=30,
                guidance_scale=8.0
            ).images[0]

            # Reload LoRA if we unloaded it
            if not use_lora and self.has_lora:
                self.pipe.load_lora_weights(self.lora_path)

            # STEP 3: EVALUATION
            print("\nSTEP 3: Running Evaluation Metrics...")
            clip_score = self.evaluator.calculate_clip_score(image, expanded_prompt)
            reasoning_score = self.evaluator.judge_reasoning(self.client, user_intent, expanded_prompt)

            return image, expanded_prompt, clip_score, reasoning_score

