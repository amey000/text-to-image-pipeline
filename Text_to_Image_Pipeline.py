LOCAL_TRAIN_DIR = "/content/lisa_training_data"

def prepare_colab_training_subset(sample_limit=5000):
    """
    Mounts Drive and moves a subset of unzipped images to local disk
    to ensure training speed.
    """
    # 1. Mount Drive
    if not os.path.exists('/content/drive'):
        drive.mount('/content/drive')

    # 2. Create local directory
    if not os.path.exists(LOCAL_TRAIN_DIR):
        os.makedirs(LOCAL_TRAIN_DIR)

    # 3. Load Annotations
    print("Reading COCO Annotations from Drive...")
    with open(DRIVE_ANNOTATIONS, 'r') as f:
        coco_data = json.load(f)

    id_to_file = {img['id']: img['file_name'] for img in coco_data['images']}

    # 4. Create Metadata Linker & Copy Images
    print(f"Linking and copying {sample_limit} images to local SSD...")
    metadata_path = os.path.join(LOCAL_TRAIN_DIR, "metadata.jsonl")

    count = 0
    with open(metadata_path, 'w') as f_meta:
        for ann in coco_data['annotations']:
            if count >= sample_limit:
                break

            img_id = ann['image_id']
            filename = id_to_file.get(img_id)

            if filename:
                source_path = os.path.join(DRIVE_IMAGES_DIR, filename)
                target_path = os.path.join(LOCAL_TRAIN_DIR, filename)

                # Copy the file to local storage if it exists
                if os.path.exists(source_path):
                    if not os.path.exists(target_path):
                        shutil.copy(source_path, target_path)

                    # Write to the linker file
                    line = {"file_name": filename, "text": ann['caption']}
                    f_meta.write(json.dumps(line) + "\n")
                    count += 1

    print(f"Success! {count} images and metadata.jsonl ready in {LOCAL_TRAIN_DIR}")

if __name__ == "__main__":
    prepare_colab_training_subset(sample_limit=5000)

